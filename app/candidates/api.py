from fastapi import APIRouter
from fastapi.responses import Response
from .schemas import Study,Candidate,Generate,Evaluate,Review,DataReview
from ..research.schemas import Control
from ..research.catalog import canonical

def router(lab):
    api=APIRouter(prefix='/api/candidates',tags=['AI strategy research'])
    @api.get('/status')
    def status(): return lab.status()
    @api.get('/studies')
    def studies(): return lab.studies()
    @api.post('/studies')
    def create_study(body:Study): return lab.create_study(body.model_dump(mode='json'))
    @api.get('/studies/{identifier}')
    def study(identifier:str): return lab.study(identifier)
    @api.get('/studies/{identifier}/references')
    def references(identifier:str): return lab.references(identifier)
    @api.post('/studies/{identifier}/data-review')
    def data_review(identifier:str,body:DataReview): return lab.data_review(identifier,body)
    @api.get('/versions')
    def versions(study_id:str|None=None): return lab.versions(study_id)
    @api.post('/versions')
    def version(body:Candidate): return lab.add_version(body)
    @api.get('/versions/{identifier}')
    def get_version(identifier:str): return lab.version(identifier)
    @api.get('/versions/{identifier}/evidence')
    def evidence(identifier:str): return lab.evidence(identifier)
    @api.post('/versions/{identifier}/evaluate')
    def evaluate(identifier:str,body:Evaluate): return lab.evaluate(identifier,body.request_id)
    @api.post('/versions/{identifier}/holdout')
    def holdout(identifier:str,body:Evaluate): return lab.seal(identifier,body.request_id)
    @api.post('/versions/{identifier}/review')
    def review(identifier:str,body:Review): return lab.review(identifier,body)
    @api.get('/versions/{identifier}/export')
    def export(identifier:str): return Response(canonical(lab.export(identifier)),media_type='application/json',headers={'Content-Disposition':'attachment; filename=artha-candidate-evidence.json'})
    @api.get('/generations')
    def generations(): return lab.generations()
    @api.post('/generations')
    def generate(body:Generate): return lab.generate(body)
    @api.post('/generations/{identifier}/cancel')
    def cancel_generation(identifier:str): return lab.cancel_generation(identifier)
    @api.get('/evaluations')
    def evaluations(version_id:str|None=None): return lab.evaluations(version_id)
    @api.post('/evaluations/{identifier}/control')
    def control(identifier:str,body:Control): return lab.control(identifier,body.action)
    @api.get('/audit')
    def audit(): return dict(integrity=lab.verify_audit(),events=lab.audit_events())
    return api
